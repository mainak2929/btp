"""Build the website's data file from the thesis dataset, plus Python reference values for the tests.

    python website/build.py      -> website/data.js, website/reference.json

data.js       : the latest 120 months of Nifty / Gold / Liquid returns (the rolling window the
                site starts from: the thesis table, then the 2026 months from fund NAVs), the frozen cushions, and the 2020-2025 test results per profile.
reference.json: the targets and an example plan computed by the Python engine, so
                tests/test_sip.py can check the site's JavaScript gives the same numbers.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT))

from sip.engine import _smart_split  # noqa: E402
from sip.forward_data import read_latest  # noqa: E402
from sip.optimize import optimized_cash_buffer  # noqa: E402

LOOKBACK, LO, HI = 120, 0.10, 0.70
CUSHIONS = json.loads((ROOT / "11_personal_sip" / "results" / "cushions.json").read_text(encoding="utf-8"))
LAMBDA = {"aggressive": 2, "moderate": 4, "conservative": 8}
EXAMPLE = {"amount": 10000, "holdings": [70000, 110000, 75000]}   # the form's pre-filled sample


def test_results() -> dict:
    """2020-2025 out-of-sample numbers for the Personal SIP (monthly re-fit), per profile."""
    t = pd.read_csv(ROOT / "11_personal_sip" / "results" / "personal_2020_2025.csv", index_col="Profile")
    return {p: {"xirr": round(float(t.loc[p, "Personal SIP XIRR"]), 4),
                "worst": round(float(t.loc[p, "Personal SIP worst fall"]), 4),
                "u": round(float(t.loc[p, "Personal SIP U"]), 4)} for p in CUSHIONS}


def main():
    R = read_latest()
    win = R.iloc[-LOOKBACK:]
    data = {
        "source": "Thesis dataset to Dec 2025, then month-end fund NAVs (AMFI)",
        "months": [str(m) for m in win.index],
        "returns": [[round(float(x), 8) for x in row] for row in win[["Nifty", "Gold", "Liquid"]].values],
        "cushions": CUSHIONS, "lambda": LAMBDA, "test2020_2025": test_results(),
    }
    js = "// generated by website/build.py - do not edit\nwindow.SIP_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n"
    (HERE / "data.js").write_text(js, encoding="utf-8")

    ref = {"window_end": str(win.index[-1]), "targets": {}, "plans": {}}
    h = np.array(EXAMPLE["holdings"], dtype=float)
    for p, L in CUSHIONS.items():
        w = optimized_cash_buffer(win, LO, HI, liquid=L)
        ref["targets"][p] = w.tolist()
        buy = _smart_split(h, w, EXAMPLE["amount"])
        after = h + buy
        drift = float(np.abs(after / after.sum() - w).max())
        trade = w * after.sum() - h if drift > 0.05 else buy        # 5% band, as in sip/engine.py
        ref["plans"][p] = {"buy": buy.tolist(), "drift": drift, "trade": trade.tolist()}
    ref["example"] = EXAMPLE
    (HERE / "reference.json").write_text(json.dumps(ref, indent=2), encoding="utf-8")
    print(json.dumps(ref, indent=2))


if __name__ == "__main__":
    main()
